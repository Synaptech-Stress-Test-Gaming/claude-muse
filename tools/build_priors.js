/* tools/build_priors.js: writes engine/priors.js from engine/priors.json (the page is opened from file://, where fetch() of JSON does not work).
   Run: node tools/build_priors.js   (engine/priors.test.js checks that the two files match) */
"use strict";
const fs = require("fs"), path = require("path");
const src = path.join(__dirname, "..", "engine", "priors.json"), dst = path.join(__dirname, "..", "engine", "priors.js");
function build(json) {
  return "/* engine/priors.js: GENERATED by tools/build_priors.js from engine/priors.json. Do not edit; edit the JSON and rebuild. */\n" +
    "\"use strict\";\n(function (root) {\n  const E = root.MuseEngine = root.MuseEngine || {};\n  const PRIORS = " + JSON.stringify(json, null, 2).replace(/\n/g, "\n  ") + ";\n" +
    "  E.PRIORS = PRIORS;\n  if (typeof module !== \"undefined\" && module.exports) module.exports = PRIORS;\n})(typeof window !== \"undefined\" ? window : globalThis);\n";
}
if (require.main === module) { const j = JSON.parse(fs.readFileSync(src, "utf8")); fs.writeFileSync(dst, build(j)); console.log("wrote " + path.relative(process.cwd(), dst)); }
module.exports = { build };
